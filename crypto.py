KEY_SIZE = 32       # 256-bit
NONCE_SIZE = 12     # الحجم الموصى به لـ AES-GCM


# =========================================================
# التحقق من المفتاح
# =========================================================

def validate_key(key):

    if not isinstance(key, bytes):

        raise TypeError(
            "مفتاح التشفير يجب أن يكون bytes."
        )

    if len(key) != KEY_SIZE:

        raise ValueError(
            "مفتاح التشفير يجب أن يكون 32 بايت."
        )


# =========================================================
# تشفير الرسالة
# =========================================================

def encrypt_message(
    message,
    key
):

    validate_key(key)


    if not isinstance(message, str):

        raise TypeError(
            "الرسالة يجب أن تكون نصًا."
        )


    # -----------------------------------------------------
    # إنشاء Nonce عشوائي جديد
    # -----------------------------------------------------

    nonce = os.urandom(
        NONCE_SIZE
    )


    # -----------------------------------------------------
    # إنشاء AES-GCM
    # -----------------------------------------------------

    aes = AESGCM(key)


    # -----------------------------------------------------
    # تحويل الرسالة إلى Bytes
    # -----------------------------------------------------

    plaintext = message.encode(
        "utf-8"
    )


    # -----------------------------------------------------
    # التشفير
    # -----------------------------------------------------

    ciphertext = aes.encrypt(
        nonce,
        plaintext,
        None
    )


    # -----------------------------------------------------
    # النتيجة
    # -----------------------------------------------------

    return nonce, ciphertext


# =========================================================
# فك تشفير الرسالة
# =========================================================

def decrypt_message(
    nonce,
    ciphertext,
    key
):

    validate_key(key)


    if not isinstance(nonce, bytes):

        raise TypeError(
            "Nonce يجب أن يكون bytes."
        )


    if len(nonce) != NONCE_SIZE:

        raise ValueError(
            "Nonce غير صالح."
        )


    if not isinstance(ciphertext, bytes):

        raise TypeError(
            "النص المشفر يجب أن يكون bytes."
        )


    # -----------------------------------------------------
    # إنشاء AES-GCM
    # -----------------------------------------------------

    aes = AESGCM(key)


    # -----------------------------------------------------
    # فك التشفير والتحقق
    # -----------------------------------------------------

    plaintext = aes.decrypt(
        nonce,
        ciphertext,
        None
    )


    # -----------------------------------------------------
    # تحويل النص إلى String
    # -----------------------------------------------------

    return plaintext.decode(
        "utf-8"
    )


# =========================================================
# اختبار التشفير
# =========================================================

def test_crypto():

    print("=" * 60)
    print("          اختبار نظام التشفير")
    print("=" * 60)


    # -----------------------------------------------------
    # إنشاء مفتاح اختبار عشوائي
    # -----------------------------------------------------

    key = AESGCM.generate_key(
        bit_length=256
    )


    # -----------------------------------------------------
    # الرسالة
    # -----------------------------------------------------

    original_message = (
        "هذه رسالة سرية للتجربة 🔐"
    )


    print()
    print("الرسالة الأصلية:")
    print(original_message)


    # -----------------------------------------------------
    # التشفير
    # -----------------------------------------------------

    nonce, ciphertext = encrypt_message(
        original_message,
        key
    )


    print()
    print("🟢 تم تشفير الرسالة بنجاح.")

    print()
    print("حجم النص المشفر:")
    print(len(ciphertext), "بايت")


    # -----------------------------------------------------
    # فك التشفير
    # -----------------------------------------------------

    decrypted_message = decrypt_message(
        nonce,
        ciphertext,
        key
    )


    print()
    print("الرسالة بعد فك التشفير:")
    print(decrypted_message)


    # -----------------------------------------------------
    # التحقق
    # -----------------------------------------------------

    if decrypted_message == original_message:

        print()
        print("🟢 الاختبار ناجح.")
        print("التشفير وفك التشفير يعملان بشكل صحيح.")

    else:

        print()
        print("❌ الاختبار فشل.")


    print()
    print("=" * 60)


# =========================================================
# تشغيل الاختبار
# =========================================================

if __name__ == "__main__":

    test_crypto()